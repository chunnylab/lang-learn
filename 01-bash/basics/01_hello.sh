!/bin/bash
# ============================================================
# บทที่ 1: Hello World — จุดเริ่มต้นของทุกอย่าง
# ============================================================
# บรรทัดแรกด้านบน "#!/bin/bash" เรียกว่า "shebang" (อ่านว่า ชี-แบงก์)
# มันบอกระบบว่า "ไฟล์นี้ให้รันด้วยโปรแกรม bash" 
# ต้องอยู่บรรทัดแรกสุดเสมอ ขาดไม่ได้!

# บรรทัดที่ขึ้นต้นด้วย # คือ "comment" — bash จะข้ามไป ไม่ประมวลผล
# ใช้เขียนคำอธิบายโค้ดเพื่อให้ตัวเอง (และคนอื่น) อ่านที่หลัง

# echo คือคำสั่ง "พิมพ์ข้อความออกทางหน้าจอ"
echo "สวัสดี Bash Script!"
echo "นี่คือสคริปต์แรกของฉัน"

# echo สามารถพิมพ์หลายบรรทัดได้ ใช้ -e เพื่อให้ \n (ขึ้นบรรทัดใหม่) ทำงาน
echo -e "บรรทัดที่ 1\nบรรทัดที่ 2"

# ลองพิมพ์แบบไม่มี quotes (ได้ แต่แนะนำให้ใส่ quotes เสมอ เดี๋ยวบทหน้าจะรู้ว่าทำไม)
echo ไม่มี quotes ก็พิมพ์ได้

# ============================================================
# 🏋️ แบบฝึกหัด:
# 1. เพิ่ม echo พิมพ์ชื่อของคุณเอง
# 2. ลองรันด้วยคำสั่ง: bash 01_hello.sh
#    แล้วลองรันแบบ debug: bash -x 01_hello.sh (จะเห็นว่า bash ทำงานทีละขั้น)
# ============================================================

echo "Chunny"