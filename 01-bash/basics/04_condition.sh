#!/bin/bash
# ============================================================
# บทที่ 4: เงื่อนไข (if/else) — ให้สคริปต์ตัดสินใจได้
# ============================================================

# ---------- โครงสร้างพื้นฐาน ----------
# if [ เงื่อนไข ]; then
#     ทำอะไรบางอย่าง
# elif [ เงื่อนไขอื่น ]; then
#     ทำอย่างอื่น
# else
#     ถ้าไม่มีเงื่อนไขไหนตรงเลย
# fi          <-- ปิดท้ายด้วย fi เสมอ (สะกด if ย้อนกลับ)

echo "=== เปรียบเทียบตัวเลข ==="
score=75

# ตัวดำเนินการเปรียบเทียบตัวเลข (ใช้ใน [ ] เท่านั้น):
#   -eq = เท่ากับ (equal)      -ne = ไม่เท่ากับ (not equal)
#   -gt = มากกว่า (greater)     -lt = น้อยกว่า (less)
#   -ge = มากกว่าหรือเท่า       -le = น้อยกว่าหรือเท่า
if [ $score -ge 80 ]; then
    echo "คะแนน $score = เกรด A"
elif [ $score -ge 70 ]; then
    echo "คะแนน $score = เกรด B"
else
    echo "คะแนน $score = ยังต้องตั้งใจอีกนิด"
fi

echo ""
echo "=== เปรียบเทียบข้อความ (string) ==="
fruit="ส้ม"

# ตัวดำเนินการ string:
#   =  เท่ากัน      != ไม่เท่ากัน
#   -z ข้อความว่างเปล่า (zero length)    -n ข้อความไม่ว่าง
if [ "$fruit" = "ส้ม" ]; then
    echo "$fruit คือผลไม้สีส้ม"
fi

# ระวัง! เวลาเทียบ string ควรใส่ quotes รอบตัวแปรเสมอ: "$fruit"
# เพราะถ้าตัวแปรว่างเปล่า โค้ดจะพัง

empty_var=""
if [ -z "$empty_var" ]; then
    echo "ตัวแปรนี้ว่างเปล่า"
fi

echo ""
echo "=== ตรวจสอบไฟล์และโฟลเดอร์ ==="
# ตัวดำเนินการเช็คไฟล์ (ใช้บ่อยมากในงานจริง!):
#   -f เป็นไฟล์ที่มีอยู่    -d เป็นโฟลเดอร์     -e มีไฟล์นี้จริง (ไฟล์หรือโฟลเดอร์ก็ได้)
#   -r อ่านได้     -w เขียนได้          -x รันได้
if [ -f "README.md" ]; then
    echo "มีไฟล์ README.md ในโฟลเดอร์นี้"
else
    echo "ไม่พบไฟล์ README.md"
fi

if [ -d ".v2c" ]; then
    echo "มีโฟลเดอร์ .v2c"
fi

echo ""
echo "=== รวมหลายเงื่อนไข (&& และ ||) ==="
age=20
has_id=true    # bash ไม่มี boolean จริง ใช้คำว่า true/false แทน

# && = AND (ต้องจริงทั้งคู่)   || = OR (จริงอย่างใดอย่างหนึ่ง)
if [ $age -ge 18 ] && [ "$has_id" = "true" ]; then
    echo "ผ่านเงื่อนไข: อายุพอและมีบัตร"
fi

if [ $age -lt 15 ] || [ "$has_id" = "true" ]; then
    echo "ผ่านเงื่อนไข: อย่างน้อยหนึ่งข้อจริง"
fi

echo ""
echo "=== case ... esac (เหมือน switch-case) ==="
read -p "กรอกคำสั่ง (start/stop/status): " command
case "$command" in
    start)
        echo "กำลังเริ่มระบบ..."
        ;;
    stop)
        echo "กำลังหยุดระบบ..."
        ;;
    status)
        echo "ระบบกำลังทำงานปกติ"
        ;;
    *)   # * = กรณีอื่นๆ ที่ไม่เข้าเคสไหนเลย (เหมือน default)
        echo "ไม่รู้จักคำสั่ง: $command"
        ;;
esac

# ============================================================
# 🏋️ แบบฝึกหัด:
# 1. รับอายุจากผู้ใช้ด้วย read แล้วบอกว่า "เด็ก" (ต่ำกว่า 13),
#    "วัยรุ่น" (13-19), "ผู้ใหญ่" (20 ขึ้นไป)
# 2. เช็คว่าไฟล์ 08_backup.sh มีสิทธิ์รันได้ไหมด้วย -x
# 3. เขียน case รับชื่อผลไม้ แล้วบอกสี (มะม่วง=เขียว, ส้ม=ส้ม, องุ่น=ม่วง)
# ============================================================

read -p "อายุ =  " user_age

if [ "$user_age" -lt 13 ]; then 
    echo "เด็ก"
elif [ "$user_age" -le 19 ]; then
    echo "วัยรุ่น"
else 
    echo "ผู้ใหญ่"
fi

if [ -x 08_backup.sh ]; then
    echo "มีสิทธิ"
else
    echo "ไม่มีสิทธิ"
fi

echo ""
echo "สีผลไม้"

read -p "ชื่อผลไม้ = " fruit

if [ "$fruit" = "มะม่วง" ]; then
    echo "สีเขียว"
elif [ "$fruit" = "ส้ม" ]; then
    echo "ส้ม"
elif [ "$fruit" = "องุ่น" ]; then
    echo "ม่วง"
else 
    echo "error exit 404"
fi
