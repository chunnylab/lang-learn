#!/bin/bash
# ============================================================
# บทที่ 3: การรับค่า — จากคีย์บอร์ด (read) และจาก arguments
# ============================================================

# ---------- วิธีที่ 1: รับจาก arguments ตอนรันสคริปต์ ----------
# ตอนรัน: ./03_input.sh สมชาย 30
# ค่าที่ส่งมาเรียกว่า "arguments" หรือ "positional parameters"
#   $1 = argument ตัวที่ 1, $2 = ตัวที่ 2, ...
#   $@ = ทุก argument,  $# = จำนวน argument

echo "=== ข้อมูลจาก arguments ==="
echo "argument ที่ 1: $1"
echo "argument ที่ 2: $2"
echo "จำนวน argument ทั้งหมด: $#"

# มันควรตรวจก่อนว่าผู้ใช้ส่ง argument มาหรือไม่ (โค้ดจริงต้องมีเสมอ!)
if [ $# -eq 0 ]; then
    echo "(ไม่มี argument — ลองรันแบบนี้: ./03_input.sh สมชาย 30)"
fi

# ---------- วิธีที่ 2: ถามผู้ใช้ระหว่างสคริปต์กำลังรัน (read) ----------
# read -p "ข้อความแสดง" ชื่อตัวแปร
echo ""
echo "=== ถามข้อมูลจากผู้ใช้ ==="
read -p "กรอกชื่อของคุณ: " username
read -p "กรอกอายุของคุณ: " user_age

echo "ยินดีที่ได้รู้จักคุณ $username อายุ $user_age ปีครับ!"

# read รับหลายค่าพร้อมกันได้ (คั่นด้วยช่องว่าง)
read -p "กรอก 3 ผลไม้ที่ชอบ (คั่นด้วยเว้นวรรค): " f1 f2 f3
echo "ผลไม้ที่คุณชอบ: $f1, $f2 และ $f3"

# ============================================================
# 🏋️ แบบฝึกหัด:
# 1. รันสคริปต์แบบส่ง argument:  ./03_input.sh มะลิ 22
# 2. รันแบบไม่ส่ง argument แล้วสังเกตผลต่าง
# 3. เพิ่ม read ถาม "อาหารที่ชอบ" แล้วพิมพ์ออกมาเป็นประโยคเต็ม
# 4. ลองใช้ $@ วนลูปพิมพ์ทุก argument (ยังไม่เรียน loop ก็ลองดูก่อนได้:
#    for arg in "$@"; do echo $arg; done  — เดี๋ยวบทที่ 5 จะเข้าใจจริง)
# ============================================================

echo ""
echo "ข้อมูลผู้ใช้งาน"
read -p "ชื่อของคุณ = " username
read -p "อายุ = " age

echo "ชื่อ $username อายุ $age"

read -p "อาหารที่ชอบ" favorite_food

echo "คุณชอบ $favorite_food"

for arg in "$@"; do echo $arg; done