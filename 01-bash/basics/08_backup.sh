#!/bin/bash
# ============================================================
# บทที่ 8: โปรเจกต์จบคอร์ส — สคริปต์ Backup ไฟล์จริง!
# ============================================================
# รวมทุกอย่างที่เรียนมา: ตัวแปร, arguments, เงื่อนไข,
# ลูป, ฟังก์ชัน, อาเรย์ และคำสั่งจริง (mkdir, tar, ls)
#
# วิธีใช้:
#   ./08_backup.sh              -> สำรองไฟล์ .sh ทั้งหมดในโฟลเดอร์นี้
#   ./08_backup.sh -l           -> ดูรายการ backup ที่เคยทำไว้
# ============================================================

# ---------- ส่วนกำหนดค่า (แก้ไขได้ตรงนี้จุดเดียว) ----------
BACKUP_DIR="backups"                      # โฟลเดอร์เก็บไฟล์ backup
TIMESTAMP=$(date +%Y%m%d-%H%M%S)          # เวลาปัจจุบัน เช่น 20260908-213000
BACKUP_FILE="${BACKUP_DIR}/scripts-${TIMESTAMP}.tar.gz"

# ---------- ฟังก์ชัน ----------
log() {
    # พิมพ์ข้อความพร้อมเวลา ให้ดูเป็นระเบียบ
    echo "[$(date +%H:%M:%S)] $1"
}

show_help() {
    echo "วิธีใช้: ./08_backup.sh [ตัวเลือก]"
    echo "  (ไม่ใส่)   สำรองไฟล์ .sh ทั้งหมด"
    echo "  -l        แสดงรายการ backup ที่มี"
    echo "  -h        แสดงวิธีใช้นี้"
}

list_backups() {
    if [ ! -d "$BACKUP_DIR" ]; then
        log "ยังไม่เคยมีการ backup เลย"
        exit 0
    fi

    local files=("$BACKUP_DIR"/*.tar.gz)    # อาเรย์เก็บชื่อไฟล์ backup

    if [ ! -f "${files[0]}" ]; then         # ถ้า wildcard ไม่เจอไฟล์เลย
        log "ยังไม่มีไฟล์ backup"
        exit 0
    fi

    log "รายการ backup ทั้งหมด:"
    local count=0
    for f in "${files[@]}"; do
        count=$((count + 1))
        local size=$(du -h "$f" | cut -f1)  # ขนาดไฟล์แบบอ่านง่าย
        echo "  $count. $(basename "$f")  ($size)"
    done
    echo "รวมทั้งหมด ${#files[@]} ไฟล์"
}

do_backup() {
    # หาไฟล์ .sh ทั้งหมดก่อน
    local scripts=(*.sh)

    if [ ! -f "${scripts[0]}" ]; then
        log "ผิดพลาด: ไม่พบไฟล์ .sh เลยในโฟลเดอร์นี้"
        exit 1
    fi

    # สร้างโฟลเดอร์ backup (ถ้ายังไม่มี) — -p คือสร้างได้แม้มีอยู่แล้ว
    mkdir -p "$BACKUP_DIR"

    log "พบ ${#scripts[@]} ไฟล์ กำลังสำรองข้อมูล..."

    # tar -czf = บีบอัดไฟล์เป็น .tar.gz
    tar -czf "$BACKUP_FILE" *.sh

    # เช็คว่าคำสั่งก่อนหน้าสำเร็จไหม ด้วย $?
    if [ $? -eq 0 ]; then
        local size=$(du -h "$BACKUP_FILE" | cut -f1)
        log "สำรองสำเร็จ! บันทึกเป็น: $BACKUP_FILE ($size)"
        log "ไฟล์ที่สำรอง:"
        for s in "${scripts[@]}"; do
            echo "   - $s"
        done
    else
        log "ผิดพลาด: การสำรองข้อมูลล้มเหลว"
        exit 1
    fi
}

# ---------- จุดเริ่มของโปรแกรม (อ่าน argument ก่อน) ----------
case "$1" in
    -l)
        list_backups
        ;;
    -h)
        show_help
        ;;
    "")
        do_backup
        ;;
    *)
        echo "ไม่รู้จักตัวเลือก: $1"
        show_help
        exit 1
        ;;
esac

# ============================================================
# 🎓 แนวคิดใหม่ที่โผล่ในไฟล์นี้:
#   mkdir -p     สร้างโฟลเดอร์ (ไม่ error แม้มีอยู่แล้ว)
#   tar -czf     บีบอัดหลายไฟล์เป็นไฟล์เดียว (.tar.gz)
#   du -h        ดูขนาดไฟล์
#   basename     ตัด path เหลือแค่ชื่อไฟล์
#   cut -f1      เลือกคอลัมน์ที่ 1 ของ output
#   exit         จบสคริปต์พร้อมรหัสสถานะ (0=ปกติ, 1=ผิดพลาด)
#
# 🏋️ แบบฝึกหัดต่อยอด:
# 1. เพิ่มตัวเลือก -r ที่ "กู้คืน" backup ล่าสุด (แกะ tar กลับมา: tar -xzf)
# 2. เพิ่มการนับว่าตอนนี้มีกี่ไฟล์ backup ถ้าเกิน 5 ให้ลบอันเก่าสุด
# 3. ทำให้รับชื่อโฟลเดอร์จาก argument ได้: ./08_backup.sh <โฟลเดอร์>
# ============================================================
