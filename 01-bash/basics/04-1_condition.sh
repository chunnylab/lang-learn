#!/bin/bash
# ============================================================
# บทที่ 4 ต่อยอด (04-1): โจทย์ฝึก "flag" ตรวจสอบไฟล์และข้อความ
# ============================================================
# ไฟล์นี้เป็น "โจทย์ล้วน" — ไม่มีเนื้อหาสอน ให้เขียนคำตอบ
# ใต้โจทย์แต่ละข้อ ตรงจุดที่เขียนว่า "เขียนคำตอบใต้บรรทัดนี้"
#
# กติกา: ห้ามใช้ loop ทั้งไฟล์ (ยังไม่เรียนบทที่ 5)
#        ใช้ได้แค่ if/elif/else/case + flag + read + argument
#
# ───────── ชีทสรุป flag ที่จะได้ใช้ ─────────
# กลุ่มตรวจไฟล์/โฟลเดอร์:
#   [ -e ชื่อ ]   มีอยู่จริง (ไฟล์หรือโฟลเดอร์ก็ได้)
#   [ -f ชื่อ ]   เป็นไฟล์ธรรมดา
#   [ -d ชื่อ ]   เป็นโฟลเดอร์
#   [ -r ชื่อ ]   อ่านได้
#   [ -w ชื่อ ]   เขียนได้
#   [ -x ชื่อ ]   รันได้ (executable)
#   [ -s ชื่อ ]   มีขนาดมากกว่า 0 (ไม่ใช่ไฟล์เปล่า)
# กลุ่มตรวจข้อความ:
#   [ -z "..." ]  ข้อความว่างเปล่า (zero)
#   [ -n "..." ]  ข้อความไม่ว่าง (non-zero)
#   [ A = B ]     เท่ากัน   /   [ A != B ]  ไม่เท่ากัน
# เทคนิคผสม:
#   [ ! -f ชื่อ ]  ตรงข้าม (ใส่ ! หน้าเงื่อนไข)
#   [ เงื่อนไข1 ] && [ เงื่อนไข2 ]   ต้องจริงทั้งคู่
#   [ เงื่อนไข1 ] || [ เงื่อนไข2 ]   จริงอย่างใดอย่างหนึ่ง
#
# วิธีทดสอบ:
#   โจทย์ 1-7, 10 : รันพร้อมส่งชื่อไฟล์ เช่น  ./04-1_condition.sh data.txt
#   โจทย์ 8-9     : รันแล้วพิมพ์ตอนที่โปรแกรมถาม
#   (รันทั้งไฟล์ = ทำทุกโจทย์เรียงกัน พอถึงโจทย์ 8-9 โปรแกรมจะหยุดรอพิมพ์
#    ถ้าอยากทดสอบแค่โจทย์ต้น ๆ กด Ctrl+C ตัดได้)
# ============================================================

# ---------- เตรียมของ (รันอัตโนมัติทุกครั้ง ปล่อยไว้ได้) ----------
touch empty.txt              # ไฟล์เปล่า (ขนาด 0)
echo "มีข้อมูลอยู่ข้างใน" > data.txt
mkdir -p myfolder            # โฟลเดอร์ทดสอบ

echo ">>> พร้อมทำโจทย์แล้ว! ไฟล์ทดสอบ: empty.txt, data.txt, myfolder"
echo ""

# ============================================================
# โจทย์ 1: มีหรือไม่มี (flag: -e)
# เช็คว่าชื่อที่ส่งมาทาง argument $1 "มีอยู่จริง" ไหม
# ตัวอย่างผลลัพธ์:
#   ./04-1_condition.sh README.md  →  มีชื่อนี้อยู่จริง
#   ./04-1_condition.sh ghost.txt  →  ไม่มีชื่อนี้
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:

if [ -e "$1" ]; then
    echo "มีชื่อนี้อยู่จริง"
else
    echo "ไม่มีชื่อนี้"
fi

# ============================================================
# โจทย์ 2: ไฟล์ โฟลเดอร์ หรือไม่มีเลย (flag: -f, -d)
# บอกให้ได้ว่า $1 เป็น "ไฟล์" / "โฟลเดอร์" / "ไม่มีอยู่"
# ตัวอย่างผลลัพธ์:
#   ./04-1_condition.sh data.txt  →  เป็นไฟล์
#   ./04-1_condition.sh myfolder  →  เป็นโฟลเดอร์
#   ./04-1_condition.sh ghost.txt →  ไม่มีอยู่
# แนะนำ: if / elif / else ครบสามทางเลย
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:

if [ -f "$1" ]; then
    echo "เป็นไฟล์"
elif [ -d "$1" ]; then
    echo "เป็นโฟลเดอร์"
else
    echo "ไม่มีอยู่"
fi

# ============================================================
# โจทย์ 3: ไฟล์เปล่าหรือไม่ (flag: -s)
# เช็คว่าไฟล์ $1 เป็นไฟล์เปล่าหรือมีเนื้อหา
# ทดสอบกับทั้งสองไฟล์นี้: empty.txt และ data.txt
# ตัวอย่างผลลัพธ์:
#   ./04-1_condition.sh empty.txt  →  ไฟล์เปล่า (ไม่มีเนื้อหา)
#   ./04-1_condition.sh data.txt   →  ไฟล์มีเนื้อหา
# แนะนำ: เพิ่มกรณี "ไม่ใช่ไฟล์" ด้วย -f ก่อน จะรับมือเมื่อส่ง myfolder มา
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:

if [ ! -f "$1" ]; then
    echo "ไม่ใช่ไฟล์"
elif [ -s "$1" ]; then
    echo "ไฟล์มีเนื้อหา"
else
    echo "ไฟล์เปล่า"
fi

# ============================================================
# โจทย์ 4: มีสิทธิ์รันไหม (flag: -x)
# เช็คว่าไฟล์ $1 รันได้ไหม
#   ถ้ารันได้  →  "รันได้"
#   ถ้ารันไม่ได้ →  "ยังรันไม่ได้ ลองสั่ง: chmod +x ชื่อไฟล์"
#                  (แค่ echo บอกคำแนะนำ ไม่ต้องสั่ง chmod จริง)
# ทดสอบ: ./04-1_condition.sh 01_hello.sh   (ต้องรันได้)
#        ./04-1_condition.sh data.txt       (ต้องรันไม่ได้)
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:

if [ -x "$1" ]; then
    echo "รันได้"
else
    echo "ยังรันไม่ได้ ลองสั่ง: chmod +x ชื่อไฟล์"
fi

# ============================================================
# โจทย์ 5: อ่านได้ไหม เขียนได้ไหม (flag: -r, -w)
# รายงาน 2 บรรทัดแยกกันสำหรับไฟล์ $1:
#   บรรทัดแรก: อ่านได้ / อ่านไม่ได้
#   บรรทัดสอง: เขียนได้ / เขียนไม่ได้
# แนะนำ: ใช้ if สองอัน "แยกกัน" ไม่ใช่ if/elif
#        เพราะสองเรื่องนี้ไม่เกี่ยวกัน (อ่านได้+เขียนได้พร้อมกันได้)
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:

if [ -r "$1" ]; then
    echo "อ่านได้"
else
    echo "อ่านไม่ได้"
fi

if [ -w "$1" ]; then
    echo "เขียนได้"
else 
    echo "เขียนไม่ได้"
fi
# ============================================================
# โจทย์ 6: ถ้ายังไม่มีค่อยสร้าง (เทคนิค: ! เนกาชัน)
# โปรแกรมจริงมักใช้แพทเทิร์นนี้สร้างไฟล์ config เริ่มต้น
#   ถ้า "ไม่มี" ไฟล์ config.txt  →  สร้างด้วยคำสั่ง touch แล้วแจ้ง "สร้าง config ใหม่แล้ว"
#   ถ้ามีแล้ว                     →  แจ้ง "มี config แล้ว ใช้อันเดิม"
# ทดสอบ: รันครั้งแรกจะสร้าง รันครั้งที่สองจะเจอว่ามีแล้ว
# แนะนำ: [ ! -f config.txt ]  = "ถ้าไฟล์นี้ไม่มี"
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:

if [ ! -f "config.txt" ]; then
    touch config.txt
    echo "สร้างไฟล์ config ใหม่แล้ว"
else
    echo "มี config แล้ว ใช้อันเดิม"
fi

# ============================================================
# โจทย์ 7: ตรวจครบจึงผ่าน (เทคนิค: && หลายเงื่อนไข)
# ตรวจว่า $1 เป็น "สคริปต์ที่พร้อมรัน" ต้องผ่านครบ 3 อย่าง:
#   เป็นไฟล์ และ อ่านได้ และ รันได้
#   ครบ    →  "สคริปต์พร้อมรันเลย!"
#   ไม่ครบ  →  "ยังไม่พร้อม"
# ทดสอบ: ./04-1_condition.sh 01_hello.sh   (ต้องพร้อม)
#        ./04-1_condition.sh data.txt       (ต้องไม่พร้อม)
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:

if [ -f "$1" ] && [ -r "$1" ] && [ -x "$1" ]; then
    echo "สคริปพร้อมแล้วรันเลย!"
else
    echo "ยังไม่พร้อม"
fi
# ============================================================
# โจทย์ 8: กรอกชื่อจริงเปล่า (flag: -z + read)
# ถามชื่อผู้ใช้ด้วย read แล้ว:
#   ถ้าไม่ได้พิมพ์อะไรเลย (ข้อความว่าง) →  "คุณไม่ได้กรอกชื่อสักหน่อย!"
#   ถ้ากรอกมา                        →  "ยินดีที่ได้รู้จัก ชื่อ"
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:

echo""
read -p "ชื่อ = " name
if [ ! -z "$name" ]; then
    echo "ยินดีที่ได้รู้จัก $name"
else
    echo "คุณไม่ได้กรอกชื่อสักหน่อย!"
fi

# ============================================================
# โจทย์ 9: ล็อกอินจำลอง (flag: -z, = )
# สมมติรหัสผ่านเก็บไว้ในตัวแปร: correct_pass="bash123"
# ถามรหัสผ่านด้วย read แล้วตรวจ 3 กรณี:
#   ไม่ได้พิมพ์อะไรเลย  →  "ไม่ได้ใส่รหัสผ่าน"
#   ถูกต้อง             →  "เข้าสู่ระบบสำเร็จ!"
#   ผิด                 →  "รหัสผ่านไม่ถูกต้อง"
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:

echo""
correct_pass="bash123"
read -p "กรอกรหัสผ่าน = " password
if [ -z "$password" ]; then
    echo "ไม่ได้ใส่รหัสผ่าน"
elif [ "$password" = "$correct_pass" ]; then
    echo "เข้าสู่ระบบสำเร็จ!"
else
    echo "รหัสผ่านไม่ถูกต้อง"
fi
# ============================================================
# โจทย์ 10 (โบนัส): รายงานสถานะ 3 รายการ
# รายงานทีละบรรทัดว่ามีไฟล์/โฟลเดอร์เหล่านี้ไหม (ใช้ -e):
#   README.md, empty.txt, ghost.txt
# ตัวอย่างผลลัพธ์:
#   README.md : มีอยู่
#   empty.txt : มีอยู่
#   ghost.txt : ไม่มี
# แนะนำ: เขียน if สามอันแยกกัน (ยังไม่มี loop ให้ใช้ ทำมือไปก่อน
#        พอเรียนบทที่ 5 จะย้อนมาย่อโจทย์นี้เป็น loop 3 บรรทัดเอง)
# ============================================================
# เขียนคำตอบใต้บรรทัดนี้:
echo ""
if [ -e "README.md" ]; then
    echo "มีอยู่"
else
    echo "ไม่มี"
fi

if [ -e "empty.txt" ]; then
    echo "มีอยู่"
else
    echo "ไม่มี"
fi

if [ -e "ghost.txt" ]; then
    echo "มีอยู่"
else
    echo "ไม่มี"
fi


echo ""
a=50
b=10
mk() {
    if [ "$a" -ge "$b" ]; then
        echo " $a มากกว่า $b "
    else 
        echo " $a น้อยกว่า $b "
    fi
}

mk

