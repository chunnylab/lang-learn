#!/bin/bash
# ============================================================
# บทที่ 6: ฟังก์ชัน (Functions) — แพ็คโค้ดให้ใช้ซ้ำได้
# ============================================================

# ---------- การสร้างฟังก์ชัน ----------
# รูปแบบ: ชื่อฟังก์ชัน() { โค้ด }
# นิยมประกาศไว้ด้านบนของสคริปต์ แล้วค่อยเรียกใช้ด้านล่าง

greet() {
    echo "สวัสดีครับ!"
}

# อีกรูปแบบหนึ่ง (ผลเหมือนกัน เลือกใช้แบบเดียวให้ทั้งโปรเจกต์)
function farewell() {
    echo "แล้วพบกันใหม่ครับ!"
}

echo "=== เรียกใช้ฟังก์ชัน ==="
greet
farewell

# ---------- ฟังก์ชันที่รับค่า (parameters) ----------
# ภายในฟังก์ชันจะใช้ $1, $2 ... รับค่า เหมือน argument ของสคริปต์เลย

greet_person() {
    local person="$1"        # local = ตัวแปรที่ใช้ได้เฉพาะในฟังก์ชันนี้
    local greeting_word="$2"
    echo "$greeting_word คุณ $person!"
}

echo ""
echo "=== ฟังก์ชันที่รับค่า ==="
greet_person "สมชาย" "หวัดดี"
greet_person "สมหญิง" "สวัสดี"

# ---------- ฟังก์ชันที่คืนค่า (return value) ----------
# วิธีที่นิยม: ฟังก์ชัน echo ค่าออกมา แล้วผู้เรียกเก็บด้วย $()

add() {
    local result=$(( $1 + $2 ))
    echo $result             # ส่งค่าออกทาง echo
}

sum=$(add 10 20)             # เก็บค่าที่ฟังก์ชัน echo ออกมา
echo ""
echo "=== ฟังก์ชันที่คืนค่า ==="
echo "10 + 20 = $sum"
echo "5 + 7 = $(add 5 7)"    # ใช้ตรง ๆ ใน echo ก็ได้

# อีกวิธี: return ใช้คืน "รหัสสถานะ" (0 = สำเร็จ, 1-255 = ผิดพลาด)
# เหมือนกับ $? ที่เรียนในบทที่ 2

is_adult() {
    if [ $1 -ge 20 ]; then
        return 0    # ความหมาย: จริง/สำเร็จ
    else
        return 1    # ความหมาย: เท็จ/ล้มเหลว
    fi
}

echo ""
echo "=== ใช้ return เป็นเงื่อนไข ==="
if is_adult 25; then
    echo "อายุ 25 เป็นผู้ใหญ่"
fi
if is_adult 15; then
    echo "ไม่มีวันพิมพ์บรรทัดนี้"
else
    echo "อายุ 15 ยังไม่ใช่ผู้ใหญ่"
fi

# ---------- ตัวอย่างจริง: ฟังก์ชันเช็คไฟล์ ----------
check_file() {
    if [ -f "$1" ]; then
        echo "[มีไฟล์] $1"
        return 0
    else
        echo "[ไม่มีไฟล์] $1"
        return 1
    fi
}

echo ""
echo "=== ใช้ฟังก์ชันตรวจไฟล์ ==="
check_file "README.md"
check_file "ไม่มีไฟล์นี้.txt"

# จุดสังเกตสำคัญ! ตอนนี้สคริปต์จบด้วย exit code 1
# เพราะคำสั่งสุดท้าย (check_file) คืนค่า 1 (ไม่พบไฟล์)
# bash จะใช้ exit status ของ "คำสั่งสุดท้าย" เป็นของสคริปต์ทั้งหมด
# ในโปรแกรมจริง เรามักปิดท้ายด้วย exit 0 เพื่อบอกว่า "สคริปต์จบอย่างปกติ"

# ============================================================
# 🏋️ แบบฝึกหัด:
# 1. เขียนฟังก์ชัน multiply ที่รับเลข 2 ตัว แล้วคืนค่าผลคูณ
# 2. เขียนฟังก์ชัน max ที่รับเลข 2 ตัว แล้วคืนค่าที่มากกว่า
# 3. เขียนฟังก์ชัน countdown ที่รับตัวเลข แล้วนับถอยหลังถึง 1
#    (รวมทักษะ for จากบทที่ 5)
# ============================================================

multiply() {
    local a=$1
    local b=$2
    echo "$((a * b))"
}

total=$(multiply 4 5)
echo "$total"

max() {
    local a=$1
    local b=$2
    if [ "$a" -ge "$b" ]; then
        echo "$a"
    else
        echo "$b"
    fi
}
total=$((max 4 5))
echo "$total"