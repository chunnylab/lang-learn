#!/bin/bash
# ============================================================
# บทที่ 2: ตัวแปร (Variables) — กล่องเก็บข้อมูล
# ============================================================

# ---------- การประกาศตัวแปร ----------
# รูปแบบ: ชื่อ="ค่า"  (สำคัญ: ห้ามมีช่องว่างรอบเครื่องหมาย = เด็ดขาด!)
name="Chunny"        # ✅ ถูก
age=25               # ตัวเลขไม่ต้องใส่ quotes ก็ได้
# age = 25           # ❌ ผิด! มีช่องว่าง bash จะคิดว่า age เป็นคำสั่ง

# ---------- การใช้ตัวแปร ----------
# ใช้เครื่องหมาย $ หน้าชื่อตัวแปรเพื่ออ้างถึงค่า
echo "สวัสดี $name"          # double quotes: ตัวแปรจะถูก "แทนค่า"
echo 'สวัสดี $name'          # single quotes: พิมพ์ตาม literal ไม่แทนค่า

# ข้อความต่อเนื่อง — ใช้ ${ } เพื่อบอกขอบเขตชัดเจน (แนะนำให้ใช้เสมอ)
fruit="มะม่วง"
echo "ฉันชอบกิน ${fruit}กับข้าวเหนียว"   # ${fruit} ชัดเจนว่าชื่อตัวแปรคือ fruit
# ถ้าเขียน "$fruitกับข้าว" bash จะหาตัวแปรชื่อ fruitกับข้าว (ผิด!)

# ---------- การเก็บผลลัพธ์จากคำสั่ง (Command Substitution) ----------
# รูปแบบ: $(คำสั่ง) — "รันคำสั่งข้างในก่อน แล้วเอาผลลัพธ์มาเก็บในตัวแปร"
today=$(date +%Y-%m-%d)          # วันที่วันนี้
current_folder=$(pwd)            # โฟลเดอร์ปัจจุบัน
file_count=$(ls | wc -l)         # นับจำนวนไฟล์ในโฟลเดอร์นี้

echo "วันนี้วันที่: $today"
echo "กำลังอยู่ในโฟลเดอร์: $current_folder"
echo "ในโฟลเดอร์นี้มี $file_count รายการ"

# ---------- ตัวแปรพิเศษที่ควรรู้ ----------
echo "--- ตัวแปรพิเศษ ---"
echo "PID ของสคริปต์นี้: $$"         # process id
echo "ค่า exit status ของคำสั่งก่อนหน้า: $?"   # 0 = สำเร็จ, อื่นๆ = ผิดพลาด

# ---------- แก้ไขค่าตัวแปร ----------
count=10
count=$((count + 5))     # รูปแบบ $(( )) ใช้คำนวณเลข
echo "10 + 5 = $count"

# ============================================================
# 🏋️ แบบฝึกหัด:
# 1. สร้างตัวแปรเก็บชื่อเมืองที่คุณอยู่ แล้วพิมพ์ออกมา
# 2. สร้างตัวแปร 2 ตัวเป็นตัวเลข แล้วบวก ลบ คูณ หาร ด้วย $(( ))
#    เครื่องหมาย: + - * /  (หารเอาเศษใช้ %)
# 3. ลองประกาศตัวแปรผิดแบบมีช่องว่าง: city = "กรุงเทพ" แล้วรันดูว่า error ว่าอะไร
# ============================================================

city="Bangkok"
echo "ชื่อเมืองที่ผมอยู่คือ ${city} ครับ"

A=1
B=2
final=$((A + B))
echo "$A + $B = $final"
