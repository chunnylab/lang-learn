#!/bin/bash
# ============================================================
# บทที่ 7: อาเรย์ (Arrays) — เก็บหลายค่าในตัวแปรเดียว
# ============================================================

# ---------- การสร้างอาเรย์ ----------
fruits=("มะม่วง" "ส้ม" "กล้วย" "แตงโม")

# ---------- การเข้าถึงข้อมูล ----------
# สำคัญ: ต้องใส่ ${ } รอบ และ index เริ่มที่ 0 (ไม่ใช่ 1!)
echo "=== การเข้าถึงสมาชิก ==="
echo "ตัวแรก (index 0): ${fruits[0]}"
echo "ตัวที่สอง (index 1): ${fruits[1]}"
echo "ตัวสุดท้าย (index 3): ${fruits[3]}"

# เข้าถึงทั้งหมด: ${ชื่อ[@]}
echo "ทั้งหมด: ${fruits[@]}"

# ---------- ดูขนาดอาเรย์ ----------
echo ""
echo "=== ขนาดอาเรย์ ==="
echo "มีทั้งหมด ${#fruits[@]} ผลไม้"

# ---------- แก้ไขและเพิ่มข้อมูล ----------
echo ""
echo "=== แก้ไขและเพิ่มข้อมูล ==="
fruits[1]="ส้มโอ"                 # แก้ค่า (ห้ามมีช่องว่างรอบ = เหมือนตัวแปรปกติ)
echo "index 1 ตอนนี้เป็น: ${fruits[1]}"

fruits+=("มังคุด" "ลิ้นจี่")       # เพิ่มท้ายอาเรย์ด้วย +=
echo "หลังเพิ่ม: ${fruits[@]}"
echo "ตอนนี้มี ${#fruits[@]} ผลไม้"

# ---------- วนลูปอาเรย์ (ใช้บ่อยที่สุด!) ----------
echo ""
echo "=== วนลูปอาเรย์ ==="
for fruit in "${fruits[@]}"; do
    echo "- $fruit"
done

# วนลูปพร้อม index ด้วย ${!ชื่อ[@]}
echo ""
echo "=== วนลูปพร้อม index ==="
for i in "${!fruits[@]}"; do
    echo "index $i = ${fruits[$i]}"
done

# ---------- อาเรย์ตัวเลข ----------
echo ""
echo "=== ตัวอย่างรวม: หาค่าเฉลี่ย ==="
scores=(80 95 72 88 60)

total=0
for s in "${scores[@]}"; do
    total=$((total + s))
done

count=${#scores[@]}
average=$((total / count))
echo "คะแนน: ${scores[@]}"
echo "รวม = $total, เฉลี่ย = $average"

# หาค่ามากสุด
max=${scores[0]}
for s in "${scores[@]}"; do
    if [ $s -gt $max ]; then
        max=$s
    fi
done
echo "ค่ามากสุด = $max"

# ============================================================
# 🏋️ แบบฝึกหัด:
# 1. สร้างอาเรย์ชื่อสัตว์ 5 ตัว แล้วพิมพ์เฉพาะตัวที่ index คู่
# 2. หาค่าน้อยสุดจากอาเรย์ scores ด้านบน (ก็อปโค้ด max มาแก้)
# 3. สร้างอาเรย์เลข 1-10 แล้วพิมพ์เฉพาะเลขคู่ (ใช้ % ในการเช็ค)
# ============================================================
